def cell10_execute_pending(completed):
    segment_id = uuid.uuid4().hex
    segment = cell10_directory / ("segment_" + segment_id)
    segment.mkdir(exist_ok=False)
    journal = segment / "blocks.jsonl"
    cell10_module.immutable(segment / "started.json", {
        "segment_id": segment_id, "design_id": cell10_id,
        "started_at_utc": datetime.now(timezone.utc).isoformat(), "environment": cell9_environment(),
        "previously_completed_blocks": len(completed),
    })
    runner, active_replicate, previous, rows, task = None, None, "0" * 64, [], None
    status, new_blocks = "INTERRUPTED", 0
    started = time.monotonic()
    try:
        with journal.open("xb") as handle:
            for task in cell10_tasks:
                if cell10_module.task_id(task) in completed:
                    continue
                rows = []
                replicate = task["record"]["replicate"]
                if active_replicate != replicate:
                    if runner is not None:
                        runner.close()
                    runner = RUNNER.Runner(cell10_factory, AUTH, MLKEM, KEM, TRACE, AUTH_ENTRIES, EXPERIMENT_PLAN)
                    active_replicate = replicate
                    cell10_module.immutable(segment / f"keygen_rep{replicate}.json", {
                        "keygen_ns": runner.keygen_ns, "replicate": replicate, "no_key_material_saved": True})
                    warmup = [record for record in TRACE.generate(EXPERIMENT_PLAN, "warmup", 14, replicate=replicate)
                              if record["scenario_id"] == "iid_p20"]
                    with (segment / f"warmup_rep{replicate}.jsonl").open("x", encoding="utf-8") as warm_handle:
                        for record in warmup:
                            for row in runner.block(record, "warmup"):
                                warm_handle.write(json.dumps(dict(row, is_final_benchmark=False,
                                                                  segment_id=segment_id), allow_nan=False) + "\n")
                if task["family"] == "memory":
                    producer = cell10_module.memory_block(cell10_factory, AUTH, MLKEM, KEM, TRACE,
                                                         AUTH_ENTRIES, runner, task)
                else:
                    producer = runner.block(task["record"], task["family"], budget=task["budget"])
                cell10_collect(producer, rows)
                for row in rows:
                    row.update(design_id=cell10_id, segment_id=segment_id, is_final_benchmark=True,
                               latency_member=task["family"] == "primary" and row["scenario_id"] == "iid_p20"
                               and row["trial_id"] < cell10_design["latency_n"],
                               loss_member=task["family"] == "primary" and row["trial_id"] < cell10_design["loss_n"])
                cell10_validate(rows, task)
                previous = cell10_module.append_block(handle, task, rows, previous)
                completed.add(cell10_module.task_id(task))
                new_blocks += 1
                if new_blocks % 50 == 0:
                    print(f"Cell 10: {len(completed)}/{len(cell10_tasks)} blocks; rep={replicate}; "
                          f"{task['family']}; segment={(time.monotonic()-started)/60:.1f} phút", flush=True)
        status = "COMPLETE_SEGMENT"
    except BaseException as error:
        interrupted = isinstance(error, (KeyboardInterrupt, SystemExit))
        status = "INTERRUPTED" if interrupted else "FATAL"
        failed = getattr(error, "row", None)
        cell10_module.immutable(segment / ("interrupted.json" if interrupted else "fatal.json"), {
            "status": status, "error_type": type(error).__name__,
            "task_id": cell10_module.task_id(task) if task is not None else None,
            "uncommitted_rows": rows, "failed_method_row": failed,
            "rule": "preserve_uncommitted_rows_do_not_use_as_final_complete_paired_block",
        })
        print("Cell 10 dừng:", status, "| Dữ liệu giữ tại", segment, flush=True)
        raise
    finally:
        if runner is not None:
            runner.close()
        if journal.exists():
            cell10_module.immutable(segment / "finished.json", {
                "status": status, "journal_sha256": cell10_module.file_sha(journal),
                "finished_at_utc": datetime.now(timezone.utc).isoformat(),
                "additional_files": {path.name: cell10_module.file_sha(path) for path in segment.iterdir()
                                     if path.is_file() and path.name not in ("blocks.jsonl", "finished.json")},
            })

