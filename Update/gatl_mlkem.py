def reference_mul(left, right):
    product = 0

    for bit_index in range(8):
        if (right >> bit_index) & 1:
            product ^= left << bit_index

    for degree in range(14, 7, -1):
        if (product >> degree) & 1:
            product ^= 0x11B << (degree - 8)

    return product


def combine_reference(rows, weights, dimension):
    result = [0] * dimension

    for weight, row in zip(weights, rows):
        for column, value in enumerate(row):
            result[column] ^= reference_mul(weight, value)

